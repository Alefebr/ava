# chatbot.py

def ask_chatbot(question, context=None):

    q = question.lower().strip()

    # -------------------------
    # سوالات کلی سیستم
    # -------------------------

    if "سیستم" in q and ("چی" in q or "چیه" in q or "درباره" in q):
        return """
سیستم هوشمند امنیت موزه ملی برای مدیریت و بهینه‌سازی
نیروهای امنیتی و گشت‌های حفاظتی موزه طراحی شده است.

این سیستم از دو بخش اصلی بهینه‌سازی تشکیل شده است:

1. تخصیص بهینه نگهبانان به سالن‌ها با استفاده از LP
2. مسیریابی گشت‌های امنیتی با استفاده از الگوریتم ژنتیک

همچنین یک رابط کاربری Streamlit برای مدیریت سیستم
و یک دستیار هوشمند آفلاین برای پاسخگویی به مدیر سیستم وجود دارد.
"""

    # -------------------------
    # LP
    # -------------------------

    if "برنامه ریزی خطی" in q or "lp" in q:

        return """
در بخش LP هدف، تخصیص بهینه نیروهای امنیتی به سالن‌های
مختلف موزه است.

تابع هدف:
کمینه‌سازی هزینه استفاده از نیروهای امنیتی.

محدودیت‌ها:
- هر سالن باید حداقل تعداد مشخصی نگهبان داشته باشد.
- سالن‌های دارای ریسک بالا باید نیروی بیشتری داشته باشند.
- تعداد کل نیروهای موجود محدود است.

این مسئله با استفاده از کتابخانه PuLP حل می‌شود.
"""

    # -------------------------
    # نگهبان
    # -------------------------

    if "نگهبان" in q or "نیرو" in q:

        return """
سیستم سه نوع نیروی امنیتی در نظر می‌گیرد:

1. نگهبان عادی
2. نگهبان ارشد
3. نیروی واکنش سریع

هزینه هر نیرو متفاوت است و الگوریتم LP تلاش می‌کند
با رعایت محدودیت‌های امنیتی، کم‌هزینه‌ترین تخصیص ممکن
را پیدا کند.
"""

    # -------------------------
    # ریسک
    # -------------------------

    if "ریسک" in q or "خطر" in q:

        return """
سطح ریسک هر سالن بین 1 تا 10 تعیین می‌شود.

سطح 1 یعنی ریسک بسیار پایین
سطح 10 یعنی ریسک بسیار بالا

در سیستم، سالن‌هایی که سطح ریسک آنها 8 یا بیشتر باشد،
حداقل یک نیروی امنیتی اضافی دریافت می‌کنند.
"""

    # -------------------------
    # الگوریتم ژنتیک
    # -------------------------

    if (
        "ژنتیک" in q
        or "genetic" in q
        or "ga" in q
    ):

        return """
الگوریتم ژنتیک برای پیدا کردن بهترین مسیر گشت امنیتی
بین نقاط مختلف موزه استفاده می‌شود.

مراحل الگوریتم:

1. ایجاد جمعیت اولیه مسیرها
2. محاسبه Fitness
3. انتخاب بهترین مسیرها
4. انجام Crossover
5. انجام Mutation
6. تولید نسل جدید
7. تکرار فرآیند تا رسیدن به مسیر مناسب

هدف، کمینه کردن مسافت گشت امنیتی است.
"""

    # -------------------------
    # مسیر
    # -------------------------

    if (
        "مسیر" in q
        or "گشت" in q
        or "مسیریابی" in q
    ):

        return """
بخش مسیریابی امنیتی با الگوریتم ژنتیک کار می‌کند.

نقاط مختلف موزه به عنوان نقاط گشت در نظر گرفته می‌شوند.
الگوریتم تمام مسیرهای ممکن را بررسی مستقیم نمی‌کند،
بلکه با استفاده از تکامل جمعیت، به تدریج مسیر مناسب‌تر
را پیدا می‌کند.

معیار اصلی Fitness، کوتاه‌تر بودن مسیر گشت است.
"""

    # -------------------------
    # Crossover
    # -------------------------

    if "crossover" in q or "تقاطع" in q:

        return """
Crossover یا عملگر تقاطع برای ترکیب دو مسیر والد
و ایجاد یک مسیر جدید استفاده می‌شود.

در این پروژه بخشی از مسیر والد اول گرفته شده و
بقیه نقاط از والد دوم تکمیل می‌شوند.
"""

    # -------------------------
    # Mutation
    # -------------------------

    if "mutation" in q or "جهش" in q:

        return """
Mutation یا جهش برای ایجاد تنوع در جمعیت استفاده می‌شود.

در این پروژه با احتمال مشخص، دو نقطه از مسیر با یکدیگر
جابه‌جا می‌شوند.

این کار باعث می‌شود الگوریتم در یک جواب خاص گیر نکند.
"""

    # -------------------------
    # Streamlit
    # -------------------------

    if (
        "streamlit" in q
        or "رابط کاربری" in q
        or "اپلیکیشن" in q
    ):

        return """
رابط کاربری پروژه با Streamlit پیاده‌سازی شده است.

مدیر سیستم می‌تواند:

- سالن‌ها را انتخاب کند.
- سطح ریسک سالن‌ها را مشخص کند.
- تعداد نیروهای امنیتی را تعیین کند.
- مدل LP را اجرا کند.
- الگوریتم ژنتیک را اجرا کند.
- مسیر گشت امنیتی را مشاهده کند.
- از دستیار هوشمند سوال بپرسد.
"""

    # -------------------------
    # هدف پروژه
    # -------------------------

    if "هدف" in q:

        return """
هدف اصلی پروژه، استفاده از روش‌های بهینه‌سازی برای
افزایش امنیت موزه و استفاده بهتر از منابع انسانی است.

سیستم تلاش می‌کند:

- هزینه نیروی انسانی را کاهش دهد.
- پوشش امنیتی سالن‌ها را افزایش دهد.
- مسیر گشت‌ها را بهینه کند.
- سالن‌های پرریسک را بهتر پوشش دهد.
"""

    # -------------------------
    # هزینه
    # -------------------------

    if "هزینه" in q or "کمینه" in q:

        return """
در مدل LP هدف اصلی کمینه‌سازی هزینه نیروهای امنیتی است.

هزینه هر نوع نیرو:

نگهبان عادی: 100
نگهبان ارشد: 150
نیروی واکنش سریع: 200

البته کاهش هزینه نباید باعث نقض محدودیت‌های امنیتی شود.
"""

    # -------------------------
    # امنیت
    # -------------------------

    if "امنیت" in q:

        return """
امنیت موزه در این پروژه از طریق دو تصمیم اصلی مدیریت می‌شود:

1. تخصیص بهینه نیروهای امنیتی
2. بهینه‌سازی مسیر گشت نیروها

برای سالن‌های دارای ریسک بالاتر، محدودیت‌های امنیتی
سخت‌گیرانه‌تری در مدل اعمال می‌شود.
"""

    # -------------------------
    # سوال درباره معماری
    # -------------------------

    if (
        "معماری" in q
        or "ماژول" in q
        or "ماژولار" in q
    ):

        return """
معماری پروژه به صورت ماژولار طراحی شده است.

ماژول‌های اصلی:

lp_solver.py
→ حل مسئله تخصیص نیرو

genetic_algorithm.py
→ مسیریابی گشت امنیتی

chatbot.py
→ دستیار هوشمند آفلاین

app.py
→ رابط کاربری Streamlit
"""

    # -------------------------
    # پاسخ پیش‌فرض
    # -------------------------

    return """
من دستیار آفلاین سیستم امنیت موزه هستم.

می‌توانم درباره موضوعات زیر پاسخ بدهم:

• سیستم امنیت موزه
• برنامه‌ریزی خطی LP
• تخصیص نگهبانان
• سطح ریسک سالن‌ها
• الگوریتم ژنتیک
• مسیریابی گشت
• Crossover
• Mutation
• Streamlit
• معماری پروژه
• هدف و هزینه‌های سیستم

لطفاً سوال خود را درباره یکی از این بخش‌ها بپرسید.
"""