import streamlit as st
import pandas as pd
import plotly.express as px

from lp_solver import solve_security_allocation
from genetic_algorithm import genetic_algorithm
from chatbot import ask_chatbot


# ============================================================
# تنظیمات صفحه
# ============================================================

st.set_page_config(
    page_title="سیستم هوشمند امنیت موزه",
    page_icon="🏛️",
    layout="wide"
)


# ============================================================
# عنوان اصلی
# ============================================================

st.title("🏛️ سیستم هوشمند امنیت موزه ملی")

st.subheader(
    "سیستم مدیریت امنیت موزه ملی و اماکن فرهنگی"
)

st.write(
    "این سامانه با استفاده از برنامه‌ریزی خطی، "
    "الگوریتم ژنتیک و دستیار هوشمند آفلاین، "
    "به مدیریت نیروهای امنیتی و مسیرهای گشت کمک می‌کند."
)

st.divider()


# ============================================================
# اطلاعات سالن‌ها
# ============================================================

st.header("🔐 اطلاعات سالن‌های موزه")

default_halls = [
    "سالن آثار باستانی",
    "سالن ایران باستان",
    "سالن هنر اسلامی",
    "سالن جواهرات",
    "سالن نسخ خطی",
    "سالن آثار تاریخی"
]

halls = st.multiselect(
    "سالن‌های تحت پوشش سیستم:",
    default_halls,
    default=default_halls
)

if len(halls) == 0:

    st.warning(
        "لطفاً حداقل یک سالن را انتخاب کنید."
    )

    st.stop()


# ============================================================
# تعیین سطح ریسک
# ============================================================

st.header("⚠️ تعیین سطح ریسک سالن‌ها")

risk_level = []

for hall in halls:

    risk = st.slider(
        f"سطح ریسک {hall}",
        min_value=1,
        max_value=10,
        value=5,
        key=f"risk_{hall}"
    )

    risk_level.append(risk)


# ============================================================
# نمودار سطح ریسک
# ============================================================

st.subheader("📊 نمودار سطح ریسک سالن‌ها")

risk_df = pd.DataFrame(
    {
        "سالن": halls,
        "سطح ریسک": risk_level
    }
)

fig_risk = px.bar(
    risk_df,
    x="سالن",
    y="سطح ریسک",
    text="سطح ریسک",
    title="مقایسه سطح ریسک سالن‌های موزه"
)

fig_risk.update_layout(
    xaxis_title="سالن",
    yaxis_title="سطح ریسک",
    yaxis=dict(range=[0, 10])
)

st.plotly_chart(
    fig_risk,
    use_container_width=True
)


st.divider()


# ============================================================
# برنامه‌ریزی خطی - تخصیص نیرو
# ============================================================

st.header("👮 بهینه‌سازی تخصیص نیروهای امنیتی")

number_of_guards = st.number_input(
    "حداکثر تعداد نگهبان موجود:",
    min_value=1,
    max_value=100,
    value=15
)


# ============================================================
# حداقل نیروی مورد نیاز هر سالن
# ============================================================

st.subheader("👮 حداقل نیروی موردنیاز هر سالن")

required_guards = []

for hall in halls:

    minimum = st.number_input(
        f"حداقل نگهبان برای {hall}:",
        min_value=1,
        max_value=10,
        value=1,
        key=f"minimum_{hall}"
    )

    required_guards.append(minimum)


# ============================================================
# انواع نیرو
# ============================================================

guards = [
    {
        "name": "نگهبان عادی",
        "cost": 100
    },
    {
        "name": "نگهبان ارشد",
        "cost": 150
    },
    {
        "name": "نیروی واکنش سریع",
        "cost": 200
    }
]


# ============================================================
# اجرای برنامه‌ریزی خطی
# ============================================================

if st.button(
    "🚀 اجرای بهینه‌سازی تخصیص نیرو",
    type="primary"
):

    try:

        result = solve_security_allocation(
            halls,
            guards,
            required_guards,
            risk_level,
            number_of_guards
        )

        # ----------------------------------------------------
        # وضعیت حل
        # ----------------------------------------------------

        st.success(
            f"وضعیت حل مدل: {result['status']}"
        )

        # ----------------------------------------------------
        # هزینه
        # ----------------------------------------------------

        st.metric(
            "💰 هزینه کل نیروها",
            result["objective"]
        )

        # ----------------------------------------------------
        # ساخت جدول
        # ----------------------------------------------------

        rows = []

        for item in result["allocation"]:

            for guard in item["guards"]:

                rows.append(
                    {
                        "سالن": item["hall"],
                        "نوع نیرو": guard["name"],
                        "تعداد": guard["count"]
                    }
                )

        # ----------------------------------------------------
        # نمایش جدول
        # ----------------------------------------------------

        if len(rows) > 0:

            allocation_df = pd.DataFrame(rows)

            st.subheader(
                "📋 نتیجه تخصیص نیروهای امنیتی"
            )

            st.dataframe(
                allocation_df,
                use_container_width=True
            )

            # ------------------------------------------------
            # محاسبه مجموع نیروهای هر سالن
            # ------------------------------------------------

            guard_counts = []

            for hall in halls:

                total = 0

                for item in result["allocation"]:

                    if item["hall"] == hall:

                        for guard in item["guards"]:

                            total += guard["count"]

                guard_counts.append(total)

            guard_df = pd.DataFrame(
                {
                    "سالن": halls,
                    "تعداد نیرو": guard_counts
                }
            )

            # ------------------------------------------------
            # نمودار تعداد نیرو
            # ------------------------------------------------

            st.subheader(
                "👮 نمودار تعداد نیروهای تخصیص‌یافته"
            )

            fig_guard = px.bar(
                guard_df,
                x="سالن",
                y="تعداد نیرو",
                text="تعداد نیرو",
                title="تعداد نیروهای امنیتی اختصاص‌یافته به هر سالن"
            )

            fig_guard.update_layout(
                xaxis_title="سالن",
                yaxis_title="تعداد نیرو"
            )

            st.plotly_chart(
                fig_guard,
                use_container_width=True
            )

        else:

            st.warning(
                "مدل هیچ نیرویی تخصیص نداده است."
            )

    except Exception as error:

        st.error(
            f"خطا در اجرای مدل برنامه‌ریزی خطی: {error}"
        )


st.divider()


# ============================================================
# الگوریتم ژنتیک
# ============================================================

st.header("🚨 مسیریابی گشت امنیتی")

st.write(
    "الگوریتم ژنتیک بهترین مسیر گشت بین نقاط مختلف موزه "
    "را پیدا می‌کند."
)


# ============================================================
# نقاط موزه
# ============================================================

locations = {

    "ورودی اصلی":
        (0, 0),

    "سالن باستان":
        (2, 4),

    "سالن جواهرات":
        (6, 5),

    "سالن نسخ خطی":
        (8, 2),

    "سالن هنر اسلامی":
        (5, 1),

    "خروجی اضطراری":
        (1, 7)
}


# ============================================================
# انتخاب نقاط گشت
# ============================================================

selected_locations = st.multiselect(
    "نقاط تحت گشت:",
    list(locations.keys()),
    default=list(locations.keys())
)


# ============================================================
# اجرای الگوریتم ژنتیک
# ============================================================

if st.button(
    "🧬 اجرای الگوریتم ژنتیک"
):

    if len(selected_locations) < 2:

        st.warning(
            "برای اجرای الگوریتم حداقل دو نقطه انتخاب کنید."
        )

    else:

        try:

            # ------------------------------------------------
            # آماده‌سازی مختصات
            # ------------------------------------------------

            selected_coordinates = {
                name: locations[name]
                for name in selected_locations
            }

            names = list(
                selected_coordinates.keys()
            )

            coordinates = list(
                selected_coordinates.values()
            )

            # ------------------------------------------------
            # اجرای الگوریتم
            # ------------------------------------------------

            ga_result = genetic_algorithm(
                coordinates,
                population_size=100,
                generations=300,
                mutation_rate=0.1
            )

            # ------------------------------------------------
            # دریافت خروجی الگوریتم
            # ------------------------------------------------

            if len(ga_result) == 3:

                route = ga_result[0]
                total_distance = ga_result[1]
                history = ga_result[2]

            elif len(ga_result) == 2:

                route = ga_result[0]
                total_distance = ga_result[1]

                history = [
                    total_distance
                    for _ in range(300)
                ]

            else:

                raise ValueError(
                    "خروجی الگوریتم ژنتیک نامعتبر است."
                )

            # ------------------------------------------------
            # پیام موفقیت
            # ------------------------------------------------

            st.success(
                "✅ بهترین مسیر گشت امنیتی با موفقیت پیدا شد."
            )

            # ------------------------------------------------
            # تبدیل شماره نقاط به نام
            # ------------------------------------------------

            route_names = []

            for index in route:

                route_names.append(
                    names[index]
                )

            # برگشت به نقطه اول

            route_names.append(
                route_names[0]
            )

            # ------------------------------------------------
            # نمایش مسیر
            # ------------------------------------------------

            st.subheader(
                "🗺️ مسیر پیشنهادی گشت امنیتی"
            )

            st.info(
                " ➜ ".join(route_names)
            )

            # ------------------------------------------------
            # نمایش مسافت
            # ------------------------------------------------

            st.metric(
                "📏 مسافت کل مسیر",
                round(total_distance, 2)
            )

            # =================================================
            # نمودار مسیر گشت
            # =================================================

            route_coordinates = []

            for index in route:

                route_coordinates.append(
                    coordinates[index]
                )

            # برگشت به نقطه اول

            route_coordinates.append(
                route_coordinates[0]
            )

            route_x = []

            route_y = []

            for point in route_coordinates:

                route_x.append(
                    point[0]
                )

                route_y.append(
                    point[1]
                )

            route_df = pd.DataFrame(
                {
                    "X": route_x,
                    "Y": route_y
                }
            )

            fig_route = px.line(
                route_df,
                x="X",
                y="Y",
                markers=True,
                title="🗺️ مسیر گشت امنیتی"
            )

            fig_route.update_layout(
                xaxis_title="مختصات X",
                yaxis_title="مختصات Y"
            )

            st.plotly_chart(
                fig_route,
                use_container_width=True
            )

            # =================================================
            # نمودار روند الگوریتم ژنتیک
            # =================================================

            st.subheader(
                "📈 نمودار روند بهبود الگوریتم ژنتیک"
            )

            history_df = pd.DataFrame(
                {
                    "نسل": range(
                        1,
                        len(history) + 1
                    ),
                    "بهترین مسافت": history
                }
            )

            fig_ga = px.line(
                history_df,
                x="نسل",
                y="بهترین مسافت",
                title="روند بهبود بهترین مسیر در نسل‌های مختلف"
            )

            fig_ga.update_layout(
                xaxis_title="شماره نسل",
                yaxis_title="بهترین مسافت"
            )

            st.plotly_chart(
                fig_ga,
                use_container_width=True
            )

            st.success(
                "📉 نمودار بالا روند بهبود الگوریتم ژنتیک "
                "در نسل‌های مختلف را نشان می‌دهد."
            )

        except Exception as error:

            st.error(
                f"خطا در اجرای الگوریتم ژنتیک: {error}"
            )


st.divider()


# ============================================================
# دستیار هوشمند آفلاین
# ============================================================

st.header(
    "🤖 دستیار هوشمند امنیت موزه"
)

st.write(
    "این دستیار کاملاً آفلاین و Rule-Based است "
    "و برای پاسخگویی به API هوش مصنوعی یا اینترنت نیاز ندارد."
)


question = st.text_input(
    "سوال خود را از دستیار امنیت موزه بپرسید:"
)


# ============================================================
# اطلاعات مورد استفاده Chatbot
# ============================================================

context = """

موضوع سیستم:
سیستم هوشمند امنیت موزه ملی و اماکن فرهنگی.

هدف سیستم:
افزایش امنیت موزه، مدیریت ریسک، تخصیص نیروهای امنیتی
و پیدا کردن مسیر مناسب گشت.

برنامه‌ریزی خطی:
برای تخصیص بهینه نیروهای امنیتی استفاده می‌شود.

الگوریتم ژنتیک:
برای پیدا کردن مسیر مناسب گشت امنیتی استفاده می‌شود.

سطح ریسک:
سطح ریسک هر سالن بین 1 تا 10 تعیین می‌شود.

سالن‌های پرریسک:
به نیروهای امنیتی بیشتری نیاز دارند.

دستیار:
به صورت آفلاین و Rule-Based کار می‌کند.

"""


# ============================================================
# پرسش از Chatbot
# ============================================================

if st.button(
    "💬 پرسش از دستیار"
):

    if question.strip():

        try:

            answer = ask_chatbot(
                question,
                context
            )

            st.info(
                answer
            )

        except Exception as error:

            st.error(
                f"خطا در دستیار هوشمند: {error}"
            )

    else:

        st.warning(
            "لطفاً ابتدا سوال خود را وارد کنید."
        )


# ============================================================
# پایان صفحه
# ============================================================

st.divider()

st.caption(
    "🏛️ سیستم هوشمند امنیت موزه ملی و اماکن فرهنگی | پروژه دانشگاهی"
)